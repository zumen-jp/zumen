//! VBA7 の宣言・ABI の型・定数と、シーンの配置を生成する（`bindings/vba/README.md`）。

use std::fmt::Write;

use crate::boundary::Boundary;
use crate::scene::Scene;

pub const OUTPUT: &str = "bindings/vba/ZumenNative.bas";

fn parameter(ty: &str) -> Result<(&'static str, &'static str), String> {
    match ty {
        "u32" | "status" => Ok(("ByVal", "Long")),
        "size" | "bytes" | "bytes_mut" | "session" | "arrow_stream" => Ok(("ByVal", "LongPtr")),
        "session_out" => Ok(("ByRef", "LongPtr")),
        "buf" => Ok(("ByRef", "ZmBuf")),
        _ => Err(format!("VBA の引数の型 `{ty}` は未対応")),
    }
}

pub fn render(version: &str, boundary: &Boundary, scene: &Scene) -> Result<String, String> {
    let mut out = String::from(
        "Attribute VB_Name = \"ZumenNative\"\nOption Explicit\n\n' Generated by cargo xtask codegen. Do not edit.\n' Sources: schema/boundary.toml and schema/scene.toml.\n' VBA7, Windows only. Arrow is a raw pointer; no VBA callback wrapper.\n\nPublic Type ZmBuf\n    ptr As LongPtr\n    length As LongPtr\nEnd Type\n\n",
    );
    writeln!(
        out,
        "Public Const ZM_PACKAGE_VERSION As String = \"{version}\""
    )
    .unwrap();
    writeln!(
        out,
        "Public Const ZM_ABI_VERSION As Long = {}",
        boundary.versions.abi
    )
    .unwrap();
    writeln!(
        out,
        "Public Const ZM_SCHEMA_VERSION_MAJOR As Long = {}",
        boundary.versions.schema_major
    )
    .unwrap();
    writeln!(
        out,
        "Public Const ZM_SCHEMA_VERSION_MINOR As Long = {}",
        boundary.versions.schema_minor
    )
    .unwrap();
    for status in &boundary.status {
        writeln!(
            out,
            "Public Const ZM_{} As Long = {}",
            status.name.to_ascii_uppercase(),
            status.value
        )
        .unwrap();
    }
    out.push('\n');
    for function in &boundary.functions {
        if !function.targets.iter().any(|target| target == "native") {
            continue;
        }
        let void = function.returns == "void";
        let kind = if void { "Sub" } else { "Function" };
        write!(
            out,
            "Public Declare PtrSafe {kind} {} Lib \"zumen_abi{}.dll\" (",
            function.name, boundary.versions.abi
        )
        .unwrap();
        let mut params = Vec::new();
        for param in &function.params {
            let (passing, ty) = parameter(&param.ty)?;
            params.push(format!("    {passing} arg_{} As {ty}", param.name));
        }
        if !params.is_empty() {
            write!(out, " _\n{}", params.join(", _\n")).unwrap();
        }
        if void {
            out.push_str(")\n\n");
        } else {
            let (_, ty) = parameter(&function.returns)?;
            writeln!(out, ") As {ty}\n").unwrap();
        }
    }
    writeln!(
        out,
        "Public Const ZM_SCENE_MAJOR As Long = {}",
        scene.versions.major
    )
    .unwrap();
    writeln!(
        out,
        "Public Const ZM_SCENE_MINOR As Long = {}",
        scene.versions.minor
    )
    .unwrap();
    writeln!(
        out,
        "Public Const ZM_SCENE_SECTION_COUNT As Long = {}",
        scene.sections.len()
    )
    .unwrap();
    out.push_str("Public Const ZM_SCENE_NONE As Double = 4294967295#\n\n");
    for values in &scene.values {
        for item in &values.items {
            writeln!(
                out,
                "Public Const ZM_SCENE_{}_{} As Double = {}#",
                values.name.to_ascii_uppercase(),
                item.name.to_ascii_uppercase(),
                item.value
            )
            .unwrap();
        }
    }
    out.push_str("\nPublic Function ZmSceneIndex(ByVal sectionName As String) As Long\n    Select Case sectionName\n");
    for (index, section) in scene.sections.iter().enumerate() {
        writeln!(
            out,
            "        Case \"{}\": ZmSceneIndex = {index}",
            section.name
        )
        .unwrap();
    }
    out.push_str("        Case Else: Err.Raise 5, \"Zumen\", \"Unknown scene section\"\n    End Select\nEnd Function\n\n");
    for (name, string) in [("Name", true), ("Type", true), ("Width", false)] {
        writeln!(
            out,
            "Public Function ZmScene{name}(ByVal index As Long) As {}\n    Select Case index",
            if string { "String" } else { "Long" }
        )
        .unwrap();
        for (index, section) in scene.sections.iter().enumerate() {
            let value = if name == "Name" {
                format!("\"{}\"", section.name)
            } else if string {
                format!("\"{}\"", section.ty)
            } else {
                section.width.to_string()
            };
            writeln!(out, "        Case {index}: ZmScene{name} = {value}").unwrap();
        }
        out.push_str("        Case Else: Err.Raise 5, \"Zumen\", \"Unknown scene section\"\n    End Select\nEnd Function\n\n");
    }
    out.pop();
    Ok(out)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn native_declarations_keep_pointer_width_and_pass_outputs_by_reference() {
        let boundary = toml::from_str(include_str!("../../schema/boundary.toml")).unwrap();
        let scene = toml::from_str(include_str!("../../schema/scene.toml")).unwrap();
        let output = render("0.2.0", &boundary, &scene).unwrap();
        for function in &boundary.functions {
            assert_eq!(
                output.contains(&format!("{} Lib", function.name)),
                function.targets.iter().any(|target| target == "native")
            );
        }
        assert!(output.contains("ByRef arg_session As LongPtr"));
        assert!(output.contains("ByVal arg_request_len As LongPtr"));
        assert!(output.contains("ByRef arg_response As ZmBuf"));
        assert!(output.contains("ByVal arg_blob As Long"));
        assert!(output.contains("ByVal arg_out As LongPtr"));
        assert!(parameter("u64").is_err());
        assert!(output.is_ascii());
        assert!(output.lines().all(|line| line.len() < 1024));
    }
}
